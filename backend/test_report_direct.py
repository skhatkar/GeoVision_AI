from fastapi.testclient import TestClient
from app.main import app
from app.db.session import SessionLocal
from app.models.user import User
from app.core.security import hash_password, create_access_token

client = TestClient(app)

def ensure_test_user():
    db = SessionLocal()
    try:
        user = db.query(User).filter(User.email == "report_tester@geovision.ai").first()
        if not user:
            user = User(
                username="report_tester",
                email="report_tester@geovision.ai",
                password_hash=hash_password("Password123!"),
                full_name="Report Test User",
                is_active=True,
            )
            db.add(user)
            db.commit()
            db.refresh(user)
        return user.id
    finally:
        db.close()

def test_report_flow_direct():
    print("--- 1. Ensure test user & generate JWT access token ---")
    user_id = ensure_test_user()
    token = create_access_token(data={"sub": "report_tester", "email": "report_tester@geovision.ai"})
    headers = {"Authorization": f"Bearer {token}"}
    print(f"User ID {user_id} (report_tester) active. Generated access token: {token[:20]}...")

    print("\n--- 2. Fetch or Create Project ---")
    resp = client.get("/projects/", headers=headers)
    projects = resp.json()
    project_id = None
    if isinstance(projects, list) and len(projects) > 0:
        project_id = projects[0]["id"]
        print(f"Using existing project ID: {project_id}")
    else:
        new_proj = {
            "name": "Shimla Urban Planning Project",
            "description": "Smart city GIS dataset and zoning analysis",
            "status": "active"
        }
        resp = client.post("/projects/", json=new_proj, headers=headers)
        assert resp.status_code in (200, 201), f"Create project failed: {resp.text}"
        project_id = resp.json()["id"]
        print(f"Created new project ID: {project_id}")

    print("\n--- 3. Generate PDF Report ---")
    gen_payload = {
        "project_id": project_id,
        "title": "Shimla Smart City GIS Audit & Topography Report",
        "notes": "Generated by GeoVision AI Engine with terrain and layer metrics."
    }
    resp = client.post("/reports/generate", json=gen_payload, headers=headers)
    assert resp.status_code in (200, 201), f"Generate report failed ({resp.status_code}): {resp.text}"
    report_data = resp.json()
    report_id = report_data["id"]
    print(f"Report generated successfully! ID: {report_id}, File: {report_data['file_path']}")

    print("\n--- 4. List Reports for Project ---")
    resp = client.get(f"/reports/project/{project_id}", headers=headers)
    assert resp.status_code == 200, f"List reports failed: {resp.text}"
    reports_list = resp.json()
    print(f"Found {len(reports_list)} report(s) for project ID {project_id}.")

    print("\n--- 5. Download Generated PDF Report ---")
    resp = client.get(f"/reports/{report_id}/download", headers=headers)
    assert resp.status_code == 200, f"Download report failed ({resp.status_code}): {resp.text}"
    pdf_bytes = resp.content
    assert len(pdf_bytes) > 0, "PDF content is empty"
    assert pdf_bytes.startswith(b"%PDF"), "Content does not start with PDF magic bytes"
    print(f"Downloaded PDF successfully! Size: {len(pdf_bytes)} bytes.")

    print("\n--- 6. Delete Report ---")
    resp = client.delete(f"/reports/{report_id}", headers=headers)
    assert resp.status_code == 200, f"Delete report failed: {resp.text}"
    print("Deleted report successfully.")

    print("\n[OK] PART 3 (REPORT GENERATION API) PASSED ALL VERIFICATION TESTS!")

if __name__ == "__main__":
    test_report_flow_direct()
